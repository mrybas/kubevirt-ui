@router.get("", response_model=TenantListResponse)
async def list_tenants(
    request: Request,
    page: int = Query(1, ge=1),
    per_page: int = Query(50, ge=1, le=200),
    user: User = Depends(require_auth),
) -> TenantListResponse:
    """List all tenants (CAPI Clusters in tenant-* namespaces).

    Authorization (T2):
      - global admins see every tenant
      - everyone else only sees tenants whose namespace has
        kubevirt-ui.io/folder + kubevirt-ui.io/environment labels referring
        to a folder/env where the user has at least viewer access
        (is_env_viewer). Tenants without folder/env labels are legacy
        (pre-T1) → admin-only.
    """
    k8s = request.app.state.k8s_client
    await _ensure_cluster_config(k8s)

    try:
        result = await k8s.custom_api.list_cluster_custom_object(
            group=CAPI_GROUP,
            version=CAPI_VERSION,
            plural="clusters",
            label_selector="kubevirt-ui.io/tenant",
        )

        clusters = result.get("items", [])

        # T2 — non-admin path: resolve folder/env per tenant ns and filter to
        # those the user can at least view. We do this BEFORE enrichment so
        # we never pay the MachineDeployment list cost for tenants the user
        # can't see anyway.
        if not is_admin(user.groups, user):
            try:
                # load_folders raises 404 if the folders CM doesn't exist; in
                # that case no non-admin can see any tenant.
                from app.core.groups import load_folders
                folders_map = await load_folders(k8s)
            except HTTPException as e:
                if e.status_code == 404:
                    folders_map = {}
                else:
                    raise

            filtered: list[dict[str, Any]] = []
            for cluster in clusters:
                ns_name = cluster.get("metadata", {}).get("namespace", "")
                if not ns_name:
                    continue
                try:
                    folder_name, env_name = await resolve_env(k8s, ns_name)
                except HTTPException:
                    # legacy / unlabeled — admin-only
                    continue
                folder_meta = folders_map.get(folder_name)
                if not folder_meta:
                    continue
                if is_env_viewer(user, folder_meta, env_name):
                    filtered.append(cluster)
            clusters = filtered

        items = []
        for cluster in clusters:
            tenant = _parse_tenant_response(cluster)
            tenant = await _enrich_with_workers(k8s, tenant)
            tenant = await _enrich_with_control_plane(k8s, tenant)
            tenant = await _enrich_with_folder_env(k8s, tenant)
            # The list is where "Ready" is read as "usable", so the downgrade
            # matters most here. Addon health is not fetched per row (too
            # expensive); worker capacity alone covers the case that misled us.
            items.append(apply_capacity_to_status(tenant))

        total = len(items)
        start = (page - 1) * per_page
        paginated = items[start:start + per_page]
        return TenantListResponse(
            items=paginated,
            total=total,
            page=page,
            per_page=per_page,
            pages=(total + per_page - 1) // per_page,
        )

    except ApiException as e:
        if e.status == 404:
            return TenantListResponse(items=[], total=0)
        logger.error(f"Failed to list tenants: {e}")
        raise k8s_error_to_http(e, "tenant operation")


def _tenant_quota(req: Any) -> dict[str, str]:
    """What a tenant asks of its folder: its workers, and its control plane.

    The control plane is counted because it genuinely spends the same
    namespace quota the workers do — its pods live in the tenant namespace.
    Leaving it out of the number would not make it free; it would quietly eat
    the workers' headroom and show up as a worker that cannot start.

    The allowance is deliberately rough: six small containers per replica,
    defaulted to 50m/128Mi each by the namespace LimitRange.

    Sized from the request rather than measured afterwards, so the folder
    ceiling can refuse a tenant that does not fit before any of it exists.
    """
    # One worker of headroom, because replacing a worker overlaps with it.
    #
    # Sized to exactly `worker_count`, the quota refused every replacement —
    # remediation created the new Machine while the old one was still around
    # and the pod was rejected:
    #
    #   exceeded quota: tenant-tci-quota, requested: requests.memory=2.4Gi,
    #   used: 5.0Gi, limited: 5.3Gi
    #
    # so a tenant whose worker died could never get a new one. The same slack
    # is what lets a rolling worker resize proceed.
    surge = req.worker_count + 1
    cpu = surge * req.worker_vcpu + req.control_plane_replicas * _CP_CPU
    worker_memory = int(parse_quantity(req.worker_memory) or 0)
    memory = (
        surge * (
            worker_memory
            + _vmi_memory_overhead(worker_memory, req.worker_vcpu)
        )
        + req.control_plane_replicas * _CP_MEMORY
    )
    storage = surge * (parse_quantity(req.worker_disk) or 0)
    # Talos workers each clone their own root from the tenant's golden image,
    # and both are real PVCs in this namespace. Counting only `worker_disk`
    # left the quota one clone short of the cluster it was provisioning:
    # measured on a two-worker tenant, the first root bound and the second
    # stopped at
    #
    #   ErrExceededQuota ... requested: requests.storage=21474836480,
    #   used: 53687091200, limited: 64424509440
    #
    # which reads as a storage failure and is arithmetic. `surge` covers the
    # roots as well, for the same reason it covers the workers: a replacement
    # clone exists alongside the disk it replaces, and CDI stages a clone
    # through a scratch PVC of the target size.
    if req.worker_os == "talos":
        from app.api.v1.tenants_capi import _worker_root_size

        # The root clones, and only those. The golden image used to be
        # imported into this namespace and was counted here for that reason;
        # T2 moved it to a shared namespace, so counting it now reserves 20Gi
        # against a tenant for something that is not in its namespace. Same
        # defect as a96df69 — a quota that does not describe the namespace it
        # governs — with the sign reversed.
        storage += surge * (parse_quantity(_worker_root_size(req)) or 0)
    return {
        "cpu": f"{cpu:g}",
        "memory": f"{int(memory)}",
        "storage": f"{int(storage)}",
    }


async def _ensure_tenant_limit_range(k8s, ns: str) -> None:
    """Default requests for pods that declare none (the Kamaji control plane)."""
    body = client.V1LimitRange(
        metadata=client.V1ObjectMeta(
            name=f"{ns}-limits", labels={"kubevirt-ui.io/managed": "true"},
        ),
        spec=client.V1LimitRangeSpec(limits=[
            client.V1LimitRangeItem(
                type="Container",
                default_request={"cpu": "50m", "memory": "128Mi"},
            ),
        ]),
    )
    try:
        await k8s.core_api.create_namespaced_limit_range(namespace=ns, body=body)
    except ApiException as e:
        if e.status != 409:
            raise


async def _write_tenant_quota(k8s, ns: str, quota: dict[str, str]) -> None:
    """Put the tenant's own quota on its namespace.

    It is what makes the tenant visible to the folder ceiling at all —
    `_own_env_quota` sums ResourceQuota objects across namespaces carrying the
    folder label, and a tenant namespace carries it.
    """
    body = client.V1ResourceQuota(
        metadata=client.V1ObjectMeta(
            name=f"{ns}-quota", labels={"kubevirt-ui.io/managed": "true"},
        ),
        # Requests only — never `limits.*`.
        #
        # A ResourceQuota that caps a limit makes the API server *require*
        # that limit on every pod in the namespace, and the Kamaji control
        # plane declares none. Every tenant created in a folder since the
        # quota was introduced simply had no control plane:
        #
        #   pods "tstor-7f5f7655fb-nvctq" is forbidden: failed quota:
        #   tenant-tstor-quota: must specify limits.cpu for: chmod, kine,
        #   konnectivity-server, kube-apiserver, kube-controller-manager,
        #   kube-scheduler
        #
        # — the TenantControlPlane sat NotReady with zero pods, and the
        # tenant page reported Provisioning forever.
        spec=client.V1ResourceQuotaSpec(hard={
            "requests.cpu": quota["cpu"],
            "requests.memory": quota["memory"],
            "requests.storage": quota["storage"],
        }),
    )
    # Kamaji's control-plane containers declare neither requests nor limits,
    # and a quota on requests makes requests mandatory:
    #
    #   pods "tstor-…" is forbidden: failed quota: tenant-tstor-quota: must
    #   specify requests.cpu for: chmod, kine, kube-apiserver,
    #   kube-controller-manager, kube-scheduler
    #
    # A LimitRange supplying defaults is what lets both coexist. Only
    # `defaultRequest` — a defaulted *limit* would throttle the apiserver at
    # whatever number we picked.
    await _ensure_tenant_limit_range(k8s, ns)

    try:
        await k8s.core_api.create_namespaced_resource_quota(namespace=ns, body=body)
    except ApiException as e:
        if e.status != 409:
            raise
        # Already there — replace it, which is what makes scaling work: the
        # quota was written for the shape the tenant had when it was created.
        await k8s.core_api.replace_namespaced_resource_quota(
            name=f"{ns}-quota", namespace=ns, body=body,
        )


@router.post("", response_model=TenantResponse, status_code=201)
async def create_tenant(request: Request, req: TenantCreateRequest, user: User = Depends(require_auth)) -> TenantResponse:
    """Create a new tenant cluster."""
    k8s = request.app.state.k8s_client
    await _ensure_cluster_config(k8s)
    ns = _tenant_ns(req.name)

    # Before anything is created: a tenant whose service CIDR swallows the
    # host's DNS address comes up, joins, and only then loses name resolution
    # on its own nodes — long after this call returned 201.
    assert_tenant_cidrs_free(req.service_cidr, req.pod_cidr)

    # Talos preflight, also before anything is created. Both of these produce
    # a tenant that looks fine and never finishes: without CABPT the machines
    # wait for bootstrap data forever, and with masquerade every guest
    # registers as 10.0.2.2 so only the first node can join.
    if req.worker_os == "talos":
        try:
            validate_worker_binding(req.worker_network_binding)
        except ValueError as exc:
            raise HTTPException(status_code=422, detail=str(exc)) from exc
        await assert_cabpt_installed(k8s)

    # T1 — validate folder/env exist + caller has folder_admin (or global admin).
    # We don't run the namespace check below until folder/env are confirmed; this
    # guarantees we never partially-create a tenant on bad metadata.
    folder_meta = await load_folder(k8s, req.folder)  # 404 if missing
    # Bug #1 fix (BUGS-TENANT-CREATE.md): discover environments from namespace
    # labels — the folder ConfigMap doesn't carry the env list (envs are
    # backend-projected from managed namespaces stamped with kubevirt-ui.io/
    # folder + environment). Looking at folder_meta["environments"] always
    # returned an empty list, so every create rejected with "Unknown envs:
    # []". The folder_meta value is still needed for the is_folder_admin
    # ACL check below.
    try:
        ns_list = await k8s.core_api.list_namespace(
            label_selector=(
                f"{ENV_FOLDER_LABEL}={req.folder},"
                "kubevirt-ui.io/managed=true"
            ),
        )
    except ApiException as exc:
        raise k8s_error_to_http(exc, "folder environment discovery")
    env_names = sorted({
        (ns.metadata.labels or {}).get(ENV_ENVIRONMENT_LABEL)
        for ns in ns_list.items
        if ns.metadata.labels
        and ns.metadata.labels.get(ENV_ENVIRONMENT_LABEL)
    })
    if req.environment not in env_names:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=(
                f"Environment '{req.environment}' does not exist in folder "
                f"'{req.folder}'. Known envs: {env_names!r}"
            ),
        )
    if not is_folder_admin(user, folder_meta):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail=(
                f"User does not have folder_admin access on folder '{req.folder}'"
            ),
        )

    # Check if already exists
    if await _namespace_exists(k8s, ns):
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=f"Tenant '{req.name}' already exists",
        )

    # vpc_name validation kept for forward compatibility — VPC support
    # for tenant clusters is currently disabled in the UI and tenant
    # workers run on the cluster default overlay. If a client still POSTs
    # a vpc_name, we validate (exists + scoped to folder/env) so the
    # field stays well-defined for the future re-enable, but no
    # ns-attach or VPC stamping happens at create time.
    if req.vpc_name:
        try:
            vpc_cr = await k8s.custom_api.get_cluster_custom_object(
                group=KUBEOVN_API_GROUP, version=KUBEOVN_API_VERSION,
                plural="vpcs", name=req.vpc_name,
            )
        except ApiException as e:
            if e.status == 404:
                raise HTTPException(
                    status_code=400,
                    detail=f"VPC '{req.vpc_name}' does not exist",
                ) from e
            raise k8s_error_to_http(e, "VPC lookup")
        vpc_labels = (vpc_cr.get("metadata") or {}).get("labels") or {}
        vpc_folder = vpc_labels.get("kubevirt-ui.io/folder")
        vpc_env = vpc_labels.get("kubevirt-ui.io/environment")
        if vpc_folder != req.folder:
            raise HTTPException(
                status_code=400,
                detail=(
                    f"VPC '{req.vpc_name}' is not scoped to folder "
                    f"'{req.folder}' (VPC folder label: {vpc_folder!r})"
                ),
            )
        if vpc_env and vpc_env != req.environment:
            raise HTTPException(
                status_code=400,
                detail=(
                    f"VPC '{req.vpc_name}' is not scoped to environment "
                    f"'{req.environment}' (VPC env label: {vpc_env!r})"
                ),
            )

    try:
        # 1. Create namespace, stamping folder/env labels so the tenant
        #    automatically participates in Phase 2 folder-level authz.
        #    Tenant ns lives on the cluster default overlay — no
        #    ovn.kubernetes.io/logical_switch pre-stamp, no VPC attach.
        # The tenant's namespace carries the folder label, so whatever quota
        # sits on it counts toward that folder's ceiling. Without one a tenant
        # was invisible to the ceiling entirely: two tenants of 2 vCPU / 2Gi
        # each ran inside folder `acme` while `acme-dev` reported only the
        # standalone VM's usage. Sized first, checked against the ceiling
        # before anything exists, then written onto the namespace.
        tenant_quota = _tenant_quota(req)
        if req.folder:
            all_folders = _parse_all_folders(await _ensure_folders_configmap(k8s))
            await assert_within_folder_quota(
                k8s, all_folders, req.folder,
                tenant_quota["cpu"], tenant_quota["memory"], tenant_quota["storage"],
                asking=f"tenant '{req.name}'",
            )

        await _create_namespace(
            k8s, ns, req.name, req.worker_type,
            folder=req.folder, environment=req.environment,
        )
        await _write_tenant_quota(k8s, ns, tenant_quota)

        # 1b. T2 — materialise folder Phase 2 RoleBindings on the tenant ns
        #     so users with folder/env access can see worker VMs in /vms.
        #     Safe to call even when the access block is empty (reconciler
        #     deletes empty RBs).
        try:
            await reconcile_namespace_rbac(
                k8s, ns, req.folder, req.environment, folder_meta,
            )
        except Exception as exc:
            logger.warning(
                f"Failed to reconcile folder RBAC on tenant ns {ns}: {exc}"
            )

        # 2b. Provision host-side kubevirt-csi resources BEFORE CAPI:
        #    KubevirtCluster.spec.infraClusterSecretRef must point at an
        #    existing Secret when CAPK reconciles, otherwise the controller
        #    errors out. The function is idempotent so it's safe to call
        #    on retry.
        storage_info: dict[str, str] | None = None
        if req.enable_storage:
            storage_info = await create_csi_infrastructure_resources(k8s, req)

        # 2c. Talos workers: the signer's PKI and the machine secrets must
        #     exist before the control plane (which mounts the certificate)
        #     and before the machine config (which embeds the token) — hence
        #     here, ahead of the CAPI resources. The trustd route itself is
        #     created with the rest of the CAPI objects, since it is just
        #     another per-tenant ingress alongside the apiserver's.
        if req.worker_os == "talos":
            # No BootstrapProvider is created here any more (T9). Installing
            # CABPT belongs to the cluster's bootstrap, pinned, not to
            # whichever tenant happens to be created first — that version was
            # whatever the operator found newest that day. `assert_cabpt_installed`
            # above has already refused the request if it is absent.
            #
            # A VPC tenant with its own VIP needs that address inside the
            # signer certificate: the worker dials <vip>:50001 by address and
            # sends no SNI, so a DNS-only certificate fails the handshake
            # before trustd is ever asked anything. Acquiring here is safe —
            # `acquire_tenant_vip` reuses an existing Service, so the address
            # `_create_capi_resources` reads later is this same one.
            talos_vip = None
            if req.vpc_name and per_tenant_vip_enabled():
                talos_vip = await acquire_tenant_vip(
                    k8s, req.name, ns, worker_os=req.worker_os,
                )
            await ensure_talos_tenant_objects(k8s, req.name, ns, vip=talos_vip)
            # Time on the transit plane. Best-effort by design: without it the
            # public fallbacks still work wherever egress does, and failing the
            # whole create over the clock would be worse than the symptom.
            await ensure_ntp_server(k8s)
            if talos_vip:
                await ensure_tenant_ntp_service(k8s, req.name, ns, talos_vip)
            # Resolved here rather than trusted: the wizard renders the pairs
            # this same function accepts, so a mismatch means one of them has
            # drifted and the tenant would be built on an image whose kubelet
            # does not match its control plane.
            release = resolve_talos_release(req.kubernetes_version, req.talos_version)
            # One golden per Talos version for the whole cluster, in a shared
            # namespace. Two tenants of the same version import once; a tenant
            # of another version gets its own alongside, with no conflict,
            # because the version is the name.
            # The clone is performed by KubeVirt as the tenant namespace's
            # default ServiceAccount, not by us — so the permission has to be
            # granted to that subject, in the namespace holding the golden.
            await ensure_golden_clone_rbac(k8s, ns)
            await ensure_shared_golden_image(
                k8s, release.talos,
                req.worker_image_url or release.image_url,
                size=req.worker_image_size,
            )

        # 3. Create CAPI resources + Ingress.
        await _create_capi_resources(k8s, req, storage_info)

        # 4. Create addon resources (Flux HelmRelease CRs)
        catalog = await _get_addon_catalog(k8s)

        # Auto-add required addons
        addon_ids = {a.addon_id for a in req.addons}
        all_addons = list(req.addons)
        for component in catalog.components:
            if component.required and component.id not in addon_ids:
                all_addons.insert(0, TenantAddon(addon_id=component.id))

        # T4 — when tenant storage is enabled, auto-include the
        # kubevirt-csi-driver addon (idempotent: user might also tick the
        # box in the wizard; that's fine, we don't double-add).
        if req.enable_storage:
            csi_component = catalog.get_component(KUBEVIRT_CSI_ADDON_ID)
            if csi_component:
                ns_for_quota = _tenant_ns(req.name)
                # No explicit class → discover one rather than sending "",
                # which makes the tenant CSI driver fall back to the host
                # cluster default (frequently not a Ceph/RBD class).
                infra_sc = req.storage_class
                if not infra_sc:
                    infra_sc = await suggested_infra_storage_class(k8s)
                    logger.info(
                        f"Tenant {req.name!r}: no storage_class given; "
                        + (
                            f"discovered {infra_sc!r}" if infra_sc
                            else "none discovered, falling back to the host "
                                 "cluster default"
                        )
                    )
                wired = {
                    "INFRA_CLUSTER_NAMESPACE": ns_for_quota,
                    "INFRA_STORAGE_CLASS_NAME": infra_sc,
                }
                # The wizard also shows this addon as a tickable box, with
                # both fields blank. Ticking it used to skip this whole
                # block, so the driver was installed with
                # `infraClusterNamespace: ""` and every PVC in the tenant
                # failed with
                #   an empty namespace may not be set when a resource name
                #   is provided
                # — the checkbox the UI offered turned the feature off.
                # Fill in what the operator left blank instead of stepping
                # aside; anything they did type still wins.
                existing = next(
                    (a for a in all_addons if a.addon_id == KUBEVIRT_CSI_ADDON_ID),
                    None,
                )
                if existing is None:
                    all_addons.append(TenantAddon(
                        addon_id=KUBEVIRT_CSI_ADDON_ID, parameters=wired,
                    ))
                else:
                    params = dict(existing.parameters or {})
                    for key, value in wired.items():
                        if not params.get(key):
                            params[key] = value
                    existing.parameters = params
            else:
                # Catalog ConfigMap doesn't have the entry — likely the
                # k8s-bootstrap repo hasn't been re-flux'd yet. Log and
                # continue so the tenant still comes up; the operator can
                # enable the addon manually once the catalog is updated.
                logger.warning(
                    f"Tenant {req.name!r}: enable_storage=True but "
                    f"{KUBEVIRT_CSI_ADDON_ID!r} not in addon catalog — "
                    "skipping addon auto-install. Update the bootstrap repo "
                    "to seed the addon catalog with kubevirt-csi-driver."
                )

        if all_addons and catalog.git_repository_ref:
            await _create_addon_resources(k8s, req.name, all_addons, catalog)

        # Best-effort: push the infra-cluster-credentials secret into the
        # tenant cluster so the CSI controller can mount it. At create time
        # the tenant control plane is usually still cold, so this typically
        # defers to the storage-reconcile path (POST .../storage/reconcile)
        # — hence we swallow failures and never block tenant create.
        if req.enable_storage:
            ok = False
            try:
                ok = await replicate_csi_credentials_to_tenant(k8s, req.name)
            except Exception as exc:
                logger.warning(
                    f"Tenant {req.name!r}: CSI credential replication "
                    f"errored (non-fatal): {exc}"
                )
            if not ok:
                # Retry in the background until the control plane comes up,
                # so the tenant finishes wiring itself instead of sitting in
                # ContainerCreating until somebody calls reconcile by hand.
                logger.info(
                    f"Tenant {req.name!r}: CSI credential replication "
                    "deferred (control plane not reachable yet); retrying in "
                    "the background"
                )
                schedule_credential_replication(k8s, req.name)

        # Return initial status
        return TenantResponse(
            name=req.name,
            display_name=req.display_name,
            namespace=ns,
            kubernetes_version=req.kubernetes_version,
            status="Provisioning",
            phase="Pending",
            endpoint=f"https://{_endpoint_host(req.name)}",
            control_plane_replicas=req.control_plane_replicas,
            control_plane_ready=False,
            worker_type=req.worker_type,
            worker_count=req.worker_count,
            workers_ready=0,
            worker_vcpu=req.worker_vcpu,
            worker_memory=req.worker_memory,
            pod_cidr=req.pod_cidr,
            service_cidr=req.service_cidr,
            addons=[
                TenantAddonStatus(addon_id=a.addon_id, name=f"{req.name}-{a.addon_id}")
                for a in all_addons
            ],
        )

    except (ApiException, RuntimeError, HTTPException) as e:
        # B1 (T9): HTTPException must trigger cleanup too. Cleanup is now
        # trivial — every cluster-level CR (KamajiControlPlane, Cluster,
        # KubevirtCluster, MachineDeployment, KubevirtMachineTemplate,
        # KubeadmConfigTemplate, per-tenant Ingress) lives in the tenant
        # namespace, so a single ns delete cascades the entire tree.
        logger.error(f"Failed to create tenant {req.name}: {e}")
        try:
            # 2026.05.29: symmetric to delete_tenant — remove the tenant ns
            # from the VPC default subnet's spec.namespaces before dropping
            # the ns. The ns cascade does NOT touch the cluster-scoped
            # Subnet, so without this the subnet would carry a stale entry
            # for an aborted tenant.
            await _detach_tenant_ns_from_vpc_subnet(k8s, req.name)
            await _remove_cp_vpc_publication(k8s, req.name)
        except Exception:
            pass
        try:
            # Release CP demux ports if a VPC tenant got that far — the
            # allocator CM is cluster-scoped and survives the ns delete.
            if req.vpc_name:
                await release_cp_ports(k8s, req.name)
        except Exception:
            pass
        try:
            await k8s.core_api.delete_namespace(name=ns)
        except Exception:
            pass
        # Preserve the original HTTPException (its status code + detail) so the
        # caller sees the actual failure mode; only wrap unexpected
        # ApiException/RuntimeError into a generic 500.
        if isinstance(e, HTTPException):
            raise
        # An ApiException carries the only useful sentence there is — the API
        # server's own reason. Swallowing it left the UI showing "Failed to
        # create tenant" for an anti-escalation refusal that names the exact
        # missing verbs, and the only way to learn them was the backend log.
        if isinstance(e, ApiException):
            raise HTTPException(
                status_code=502 if e.status >= 500 else e.status,
                detail=f"Failed to create tenant: {_api_reason(e)}",
            ) from e
        raise HTTPException(status_code=500, detail="Failed to create tenant") from e


@router.get("/{name}", response_model=TenantResponse)
async def get_tenant(request: Request, name: str, user: User = Depends(require_auth)) -> TenantResponse:
    """Get tenant details."""
    k8s = request.app.state.k8s_client
    await require_tenant_access(k8s, user, name, level="viewer")
    await _ensure_cluster_config(k8s)
    ns = _tenant_ns(name)

    try:
        cluster = await k8s.custom_api.get_namespaced_custom_object(
            group=CAPI_GROUP,
            version=CAPI_VERSION,
            namespace=ns,
            plural="clusters",
            name=name,
        )
    except ApiException as e:
        if e.status == 404:
            raise HTTPException(status_code=404, detail=f"Tenant '{name}' not found")
        raise k8s_error_to_http(e, "tenant operation")

    addon_statuses = await _get_addon_statuses(k8s, name)
    tenant = _parse_tenant_response(cluster, addon_statuses)
    tenant = await _enrich_with_workers(k8s, tenant)
    tenant = await _enrich_with_control_plane(k8s, tenant)
    tenant = await _enrich_with_cp_address(k8s, tenant)
    tenant = await _enrich_with_worker_os(k8s, tenant)
    tenant = await _enrich_with_folder_env(k8s, tenant)
    tenant = await _enrich_with_transit_snat(k8s, tenant)
    return apply_capacity_to_status(tenant)


@router.delete("/{name}", status_code=204)
async def delete_tenant(request: Request, name: str, user: User = Depends(require_auth)) -> None:
    """Delete a tenant.

    All cluster-level CRs (KamajiControlPlane, Cluster, KubevirtCluster,
    MachineDeployment, KubevirtMachineTemplate, KubeadmConfigTemplate, the
    per-tenant apiserver Ingress/IngressRouteTCP/HTTPProxy) live in the
    tenant namespace, so the ns cascade catches every in-namespace object.

    Order:
      1. Best-effort delete of the CAPI ``Cluster`` CR so CAPI runs its
         finalizers cleanly (the ns cascade would catch it too, but giving
         CAPI a head start avoids 30s+ stuck-in-Terminating cycles).
      2. Clean up the cluster-scoped leftovers the ns cascade cannot reach
         (VPC subnet membership, CSI ClusterRoleBinding, CP demux ports).
         Every one of these is best-effort: a failure here must not skip
         step 3, or the caller gets an error while a fully running tenant —
         control plane pods, worker VMs and their volumes — stays behind.
      3. Delete the tenant ns — cascade does the rest.
    """
    k8s = request.app.state.k8s_client
    await require_tenant_access(k8s, user, name, level="admin")
    ns = _tenant_ns(name)

    if not await _namespace_exists(k8s, ns):
        raise HTTPException(status_code=404, detail=f"Tenant '{name}' not found")

    # 1. Best-effort delete of the CAPI Cluster CR — lets CAPI finalizers run
    #    before the ns cascade yanks everything out from under them. 404-
    #    tolerant: a partial-create may have skipped this step.
    try:
        await k8s.custom_api.delete_namespaced_custom_object(
            group=CAPI_GROUP, version=CAPI_VERSION,
            namespace=ns, plural="clusters", name=name,
        )
        logger.info(f"Deleted CAPI Cluster {ns}/{name}")
    except ApiException as exc:
        if exc.status == 404:
            logger.info(f"CAPI Cluster {ns}/{name} already absent; continuing")
        else:
            logger.warning(f"Failed to delete CAPI Cluster {ns}/{name}: {exc}")

    # 2. Cluster-scoped leftovers, none of which the ns cascade reaps:
    #      * the tenant's entry in the VPC default subnet's spec.namespaces
    #        (2026.05.29) — otherwise the Subnet keeps a stale entry
    #      * the per-tenant CSI ClusterRoleBinding
    #      * the tenant's CP demux ports in the cluster-wide allocator
    #        ConfigMap (no-op for default-overlay tenants that never
    #        allocated)
    #    All idempotent, and all wrapped: `release_cp_ports` re-raises
    #    non-409/404 ApiExceptions and the others can fail on a transient
    #    apiserver error, which previously aborted the request before step 3
    #    and left the tenant fully alive behind a 5xx.
    for label, cleanup in (
        ("detach tenant ns from the VPC subnet", _detach_tenant_ns_from_vpc_subnet),
        ("drop the control-plane SwitchLBRule", _remove_cp_vpc_publication),
        ("delete the CSI ClusterRoleBinding", delete_csi_cluster_role_binding),
        ("release the CP demux ports", release_cp_ports),
        ("drop the transit EIP/SNAT and its ACLs", _release_tenant_transit),
    ):
        try:
            await cleanup(k8s, name)
        except Exception as exc:
            logger.warning(
                f"Tenant {name!r}: could not {label} ({exc}); continuing "
                "teardown — the namespace delete below still runs"
            )

    # 3. Cascade-delete everything else by removing the tenant ns.
    try:
        await k8s.core_api.delete_namespace(name=ns)
    except ApiException as e:
        if e.status == 404:
            logger.info(f"Tenant ns {ns} already absent; delete complete")
            return
        logger.error(f"Failed to delete tenant {name}: {e}")
        raise k8s_error_to_http(e, "tenant operation")


async def _release_tenant_transit(k8s, tenant_name: str) -> None:
    """Give back the transit-plane objects this tenant owns.

    Its EIP address is read before the objects go, because the transit subnet's
    ACLs are keyed on the address rather than on the tenant's name. The VPC's
    own attachment and control-plane guard are deliberately left behind: other
    tenants in the same VPC are still using them, and a leftover entry costs
    nothing while a missing one costs every tenant behind it their control
    plane.
    """
    transit = transit_subnet_name()
    if not transit:
        return

    eip_address = None
    try:
        eip = await k8s.custom_api.get_cluster_custom_object(
            group=KUBEOVN_API_GROUP, version=KUBEOVN_API_VERSION,
            plural="ovn-eips", name=f"cpt-eip-{tenant_name}",
        )
        eip_address = (eip.get("status", {}) or {}).get("v4Ip")
    except ApiException as e:
        if e.status != 404:
            raise

    await remove_tenant_transit(k8s, tenant_name, transit, eip_address)


async def _rotate_worker_template(
    k8s, ns: str, md_name: str, worker_vcpu: int | None, worker_memory: str | None,
) -> str | None:
    """Resize tenant workers by rotating their KubevirtMachineTemplate.

    CAPI infra templates are immutable, and changing CPU/RAM means recreating
    the worker VMs anyway, so we copy the current template, apply the new
    domain.cpu/memory, create it under a fresh name, and repoint the
    MachineDeployment's infrastructureRef — CAPI then rolls the workers.

    Returns the new template name, or None when nothing changed.
    """
    md = await k8s.custom_api.get_namespaced_custom_object(
        group=CAPI_GROUP, version=CAPI_VERSION, namespace=ns,
        plural="machinedeployments", name=md_name,
    )
    infra_ref = (
        md.get("spec", {}).get("template", {}).get("spec", {}).get("infrastructureRef", {})
    )
    if infra_ref.get("kind") != "KubevirtMachineTemplate":
        return None
    old_tpl_name = infra_ref.get("name", "")

    tpl = await k8s.custom_api.get_namespaced_custom_object(
        group=KUBEVIRT_INFRA_GROUP, version=KUBEVIRT_INFRA_VERSION, namespace=ns,
        plural="kubevirtmachinetemplates", name=old_tpl_name,
    )
    domain = (
        tpl.get("spec", {}).get("template", {}).get("spec", {})
        .get("virtualMachineTemplate", {}).get("spec", {})
        .get("template", {}).get("spec", {}).get("domain", {})
    )
    cur_vcpu = domain.get("cpu", {}).get("cores")
    cur_mem = domain.get("memory", {}).get("guest")
    if (worker_vcpu is None or worker_vcpu == cur_vcpu) and (
        worker_memory is None or worker_memory == cur_mem
    ):
        return None  # no resource change requested

    # Build the new template: copy spec, drop server-managed metadata, resize.
    # Base the name on the MachineDeployment (not the possibly-already-suffixed
    # old template) so repeated resizes don't grow the name unbounded.
    new_name = f"{md_name}-{uuid.uuid4().hex[:5]}"
    new_tpl: dict[str, Any] = {
        "apiVersion": tpl["apiVersion"],
        "kind": tpl["kind"],
        "metadata": {"name": new_name, "namespace": ns},
        "spec": copy.deepcopy(tpl["spec"]),
    }
    new_domain = (
        new_tpl["spec"]["template"]["spec"]["virtualMachineTemplate"]["spec"]
        ["template"]["spec"]["domain"]
    )
    if worker_vcpu is not None:
        new_domain.setdefault("cpu", {})["cores"] = worker_vcpu
    if worker_memory is not None:
        new_domain.setdefault("memory", {})["guest"] = worker_memory

    await k8s.custom_api.create_namespaced_custom_object(
        group=KUBEVIRT_INFRA_GROUP, version=KUBEVIRT_INFRA_VERSION, namespace=ns,
        plural="kubevirtmachinetemplates", body=new_tpl,
    )
    return new_name


async def _plan_tenant_quota(k8s, name: str, ns: str, scale: Any) -> dict[str, str]:
    """What the tenant will need, refused here if the folder cannot cover it.

    Called *before* anything is patched. Checking afterwards left the
    MachineDeployment already scaled when the ceiling said no — the same
    half-applied state this whole path exists to avoid.

    The tenant's own current reservation is excluded from the folder's sum so
    it is not counted twice.
    """
    shape = await _current_worker_shape(k8s, ns, f"{name}-workers")
    quota = _tenant_quota(SimpleNamespace(
        worker_count=scale.worker_count,
        worker_vcpu=scale.worker_vcpu or shape["vcpu"],
        worker_memory=scale.worker_memory or shape["memory"],
        worker_disk=shape["disk"],
        control_plane_replicas=shape["cp_replicas"],
        worker_os=shape["worker_os"],
    ))

    folder = ""
    try:
        ns_obj = await k8s.core_api.read_namespace(name=ns)
        folder = (ns_obj.metadata.labels or {}).get("kubevirt-ui.io/folder", "")
    except Exception:
        pass

    if folder:
        all_folders = _parse_all_folders(await _ensure_folders_configmap(k8s))
        await assert_within_folder_quota(
            k8s, all_folders, folder,
            quota["cpu"], quota["memory"], quota["storage"],
            exclude_namespace=ns,
            asking=f"tenant '{name}'",
        )
    return quota


async def _current_worker_shape(k8s, ns: str, md_name: str) -> dict[str, Any]:
    """The shape the tenant's workers have right now, read from the objects.

    There is no bookkeeping to consult: vCPU/memory/disk live on the
    KubevirtMachineTemplate the MachineDeployment points at, and the control
    plane replica count on the KamajiControlPlane.
    """
    shape: dict[str, Any] = {
        "vcpu": 2, "memory": "2Gi", "disk": "20Gi", "cp_replicas": 1,
        # Read from the datapath, not from an annotation: the root volume says
        # what this tenant is. A DataVolume means Talos clones a root per
        # worker; a containerDisk means cloud-init. `_tenant_quota` needs it,
        # and a shim that omitted it turned every scale into a 500 —
        # AttributeError: 'SimpleNamespace' object has no attribute 'worker_os'
        # — which the page swallowed silently.
        "worker_os": "cloud-init",
    }
    try:
        md = await k8s.custom_api.get_namespaced_custom_object(
            group=CAPI_GROUP, version=CAPI_VERSION, namespace=ns,
            plural="machinedeployments", name=md_name,
        )
        ref = (((md.get("spec") or {}).get("template") or {}).get("spec") or {}).get(
            "infrastructureRef", {},
        )
        tpl = await k8s.custom_api.get_namespaced_custom_object(
            group=KUBEVIRT_INFRA_GROUP, version=KUBEVIRT_INFRA_VERSION, namespace=ns,
            plural="kubevirtmachinetemplates", name=ref.get("name", ""),
        )
        vm = (
            tpl.get("spec", {}).get("template", {}).get("spec", {})
            .get("virtualMachineTemplate", {}).get("spec", {})
        )
        domain = vm.get("template", {}).get("spec", {}).get("domain", {})
        shape["vcpu"] = domain.get("cpu", {}).get("cores") or shape["vcpu"]
        shape["memory"] = domain.get("memory", {}).get("guest") or shape["memory"]

        volumes = vm.get("template", {}).get("spec", {}).get("volumes") or []
        root = next((v for v in volumes if v.get("name") == "root"), {})
        if "dataVolume" in root:
            shape["worker_os"] = "talos"

        # `worker_disk` is the *data* disk. Taking it from the DataVolume
        # template read the root clone instead, and since the quota now counts
        # the root separately that would have charged it twice.
        data = next((v for v in volumes if v.get("name") == "data"), {})
        capacity = (data.get("emptyDisk") or {}).get("capacity")
        if capacity:
            shape["disk"] = capacity
    except Exception as e:
        logger.warning(f"Could not read worker shape in {ns}: {e}")

    try:
        cp = await k8s.custom_api.get_namespaced_custom_object(
            group=KAMAJI_CP_GROUP, version=KAMAJI_CP_VERSION, namespace=ns,
            plural="kamajicontrolplanes", name=ns.removeprefix("tenant-"),
        )
        shape["cp_replicas"] = (cp.get("spec") or {}).get("replicas") or 1
    except Exception:
        pass
    return shape


@router.post("/{name}/scale", response_model=TenantResponse)
async def scale_tenant(
    request: Request, name: str, scale: TenantScaleRequest,
    user: User = Depends(require_auth),
) -> TenantResponse:
    """Scale and/or resize tenant worker nodes."""
    k8s = request.app.state.k8s_client
    await require_tenant_access(k8s, user, name, level="member")
    ns = _tenant_ns(name)
    md_name = f"{name}-workers"

    # Ask the folder ceiling before touching anything: a refusal must leave
    # the tenant exactly as it was.
    planned_quota = await _plan_tenant_quota(k8s, name, ns, scale)

    try:
        # Resize first (rotate template), so the replica patch below lands on
        # the MachineDeployment that already points at the new template.
        new_tpl_name = await _rotate_worker_template(
            k8s, ns, md_name, scale.worker_vcpu, scale.worker_memory,
        )

        patch: dict[str, Any] = {"spec": {"replicas": scale.worker_count}}
        if new_tpl_name:
            patch["spec"].setdefault("template", {}).setdefault("spec", {})[
                "infrastructureRef"
            ] = {
                "apiVersion": f"{KUBEVIRT_INFRA_GROUP}/{KUBEVIRT_INFRA_VERSION}",
                "kind": "KubevirtMachineTemplate",
                "name": new_tpl_name,
            }

        await k8s.custom_api.patch_namespaced_custom_object(
            group=CAPI_GROUP,
            version=CAPI_VERSION,
            namespace=ns,
            plural="machinedeployments",
            name=md_name,
            body=patch,
            _content_type="application/merge-patch+json",
        )
    except ApiException as e:
        if e.status == 404:
            raise HTTPException(status_code=404, detail=f"Tenant '{name}' not found")
        raise k8s_error_to_http(e, "tenant operation")

    # Now that the shape is applied, the namespace quota follows it. Left at
    # the size it had when the tenant was created, the scale-up would land and
    # then be refused pod by pod.
    await _write_tenant_quota(k8s, ns, planned_quota)

    # `user` must be handed over explicitly: calling an endpoint function
    # directly bypasses FastAPI's dependency resolution, so its
    # `user: User = Depends(require_auth)` default arrives as the Depends
    # object itself and the first authorisation check dies with
    # `'Depends' object has no attribute 'groups'` — a 500 on every scale,
    # after the scale had already been applied.
    return await get_tenant(request, name, user=user)


