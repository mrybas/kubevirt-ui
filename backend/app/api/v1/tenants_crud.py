def _parse_tenant_response(
    cluster: dict[str, Any],
    addon_statuses: list[TenantAddonStatus] | None = None,
) -> TenantResponse:
    metadata = cluster.get("metadata", {})
    spec = cluster.get("spec", {})
    cluster_status = cluster.get("status", {})
    name = metadata.get("name", "")

    # Parse phase
    phase = cluster_status.get("phase")

    # Check Ready condition from conditions list (authoritative source)
    ready_condition_true = False
    for c in cluster_status.get("conditions", []):
        if c.get("type") == "Ready" and c.get("status") == "True":
            ready_condition_true = True
            break

    # Determine status: Ready condition takes priority over phase
    if phase == "Deleting":
        status_str = "Deleting"
    elif phase == "Failed":
        status_str = "Failed"
    elif ready_condition_true:
        status_str = "Ready"
    elif phase in ("Provisioning", "Provisioned", "Pending"):
        status_str = "Provisioning"
    else:
        status_str = phase or "Unknown"

    # Control plane
    cp_ready = cluster_status.get("controlPlaneReady", False)

    # Worker count from MachineDeployment (will be enriched later)
    infra_ready = cluster_status.get("infrastructureReady", False)

    # Parse conditions
    conditions = []
    for c in cluster_status.get("conditions", []):
        conditions.append(TenantCondition(
            type=c.get("type", ""),
            status=c.get("status", "Unknown"),
            message=c.get("message", ""),
            reason=c.get("reason", ""),
            last_transition_time=c.get("lastTransitionTime"),
        ))

    # Network
    cluster_network = spec.get("clusterNetwork", {})
    pod_cidrs = cluster_network.get("pods", {}).get("cidrBlocks", [])
    svc_cidrs = cluster_network.get("services", {}).get("cidrBlocks", [])

    return TenantResponse(
        name=name,
        display_name=metadata.get("annotations", {}).get("kubevirt-ui.io/display-name", name),
        transit_conflict=metadata.get("annotations", {}).get(
            "kubevirt-ui.io/transit-conflict"
        ),
        namespace=metadata.get("namespace", ""),
        folder=metadata.get("labels", {}).get("kubevirt-ui.io/folder", ""),
        environment=metadata.get("labels", {}).get("kubevirt-ui.io/environment", ""),
        kubernetes_version=cluster_status.get("version", ""),
        status=status_str,
        phase=phase,
        endpoint=f"https://{_endpoint_host(name)}",
        control_plane_replicas=0,
        control_plane_ready=cp_ready,
        worker_type=metadata.get("annotations", {}).get("kubevirt-ui.io/worker-type", "vm"),
        worker_count=0,
        workers_ready=0,
        worker_vcpu=0,
        worker_memory="",
        pod_cidr=pod_cidrs[0] if pod_cidrs else "",
        service_cidr=svc_cidrs[0] if svc_cidrs else "",
        enable_oidc=metadata.get("annotations", {}).get("kubevirt-ui.io/enable-oidc", "false") == "true",
        created=metadata.get("creationTimestamp"),
        conditions=conditions,
        addons=addon_statuses or [],
    )


async def _healthy_worker_count(k8s, namespace: str, fallback: int) -> int:
    """Workers whose node is actually healthy, not whose Machine says Ready.

    A Machine keeps `Ready=True` while the node behind it is gone. Measured:
    a worker VM deleted out of band was recreated by CAPK from its original
    (expired) bootstrap secret, so the new VM never rejoined — and for ten
    minutes CAPI reported

        Ready=True  BootstrapReady=True  InfrastructureReady=True
        NodeHealthy=Unknown  (Node condition Ready is Unknown)

    while the tenant's own `kubectl get nodes` showed the node NotReady with
    a stale address. `readyReplicas` counts the first three and not the
    fourth, so the UI said 2/2 for a cluster with one dead worker.

    `NodeHealthy` is the condition that tracks the node, so it is the one to
    count. Falls back to `readyReplicas` if Machines cannot be listed — a
    degraded number is better than a zero that reads as an outage.
    """
    try:
        machines = await k8s.custom_api.list_namespaced_custom_object(
            group=CAPI_GROUP, version=CAPI_VERSION,
            namespace=namespace, plural="machines",
        )
    except ApiException as e:
        logger.debug(f"Could not list Machines in {namespace}: {e}")
        return fallback

    items = machines.get("items") or []
    if not items:
        return fallback

    healthy = 0
    for m in items:
        for cond in (m.get("status", {}).get("conditions") or []):
            if cond.get("type") == "NodeHealthy" and cond.get("status") == "True":
                healthy += 1
                break
    return healthy


def apply_capacity_to_status(tenant: TenantResponse) -> TenantResponse:
    """Downgrade Ready when the tenant cannot actually run anything.

    CAPI's `Ready` is about the control plane, and it is right about it — the
    list view just means something else by the word. A tenant showing Ready at
    `0/1 workers`, with no Kubernetes version and a CNI release stuck in
    `uninstalling`, has no capacity whatsoever; the detail page said so and the
    list did not.

    Only Ready is downgraded. Failed stays Failed (worse), and Provisioning
    stays Provisioning — missing workers are expected while a cluster builds.
    """
    if tenant.status != "Ready":
        return tenant

    reasons: list[str] = []

    if tenant.worker_count and tenant.workers_ready < tenant.worker_count:
        reasons.append(f"{tenant.workers_ready}/{tenant.worker_count} workers joined")

    wedged = [a.addon_id or a.name for a in (tenant.addons or []) if not a.ready]
    if wedged:
        reasons.append("addon not reconciled: " + ", ".join(wedged))

    # A contested SNAT slot is not something the tenant recovers from on its
    # own, and it is invisible everywhere else: the cluster looks built, the
    # internet works, and only the control-plane path is dead. Say it here,
    # where someone is already asking why the tenant is not Ready.
    if tenant.transit_conflict:
        reasons.append(tenant.transit_conflict)

    # A stalled rollout keeps every existing worker healthy, so none of the
    # checks above notice it. Without this the tenant reads Ready while the
    # change the operator asked for is going nowhere.
    if tenant.rollout_stalled:
        reasons.append(tenant.rollout_stalled)

    if not reasons:
        return tenant

    tenant.status = "Degraded"
    tenant.status_detail = "; ".join(reasons)
    return tenant


async def _rollout_stall(
    k8s, namespace: str, md_spec: dict, md_status: dict,
) -> str | None:
    """Why a worker rollout is not finishing, if it is not finishing.

    A rollout that cannot start looks exactly like a healthy cluster: the old
    workers are untouched and Ready, `readyReplicas` equals `replicas`, and
    the replacement sits as a Machine with no pod. Measured in UAT
    2026-08-19 — a vCPU change through the UI's own Apply button hung this
    way for good, and the tenant went on reporting Ready 2/2.

    `updatedReplicas` is the number already on the current template, so it is
    the one field that tells old from new.
    """
    desired = md_spec.get("replicas") or 0
    # Absent is not zero: a MachineDeployment that has not been reconciled yet
    # carries no `updatedReplicas` at all, and reading that as "none updated"
    # reports every fresh tenant as stalled.
    if not desired or "updatedReplicas" not in md_status:
        return None

    updated = md_status.get("updatedReplicas") or 0
    if updated >= desired:
        return None

    stale = desired - updated
    reason = await _blocked_pod_reason(k8s, namespace)
    detail = f" — {reason}" if reason else ""
    return (
        f"worker rollout stalled: {stale} of {desired} still on the old "
        f"template{detail}"
    )


async def _blocked_pod_reason(k8s, namespace: str) -> str | None:
    """The event behind a replacement that never got a pod.

    Only read when a rollout is already known to be stuck, so the cost lands
    on the rare path rather than on every row of the tenant list.
    """
    try:
        events = await k8s.core_api.list_namespaced_event(
            namespace=namespace,
            field_selector="reason=FailedCreate",
            limit=20,
        )
    except ApiException as e:
        logger.debug(f"could not read events in {namespace}: {e}")
        return None

    for event in reversed(events.items or []):
        message = event.message or ""
        if "exceeded quota" in message:
            # The quota name and the shortfall are the actionable part; the
            # pod name changes on every retry and only adds noise.
            return "namespace quota has no room for the replacement pod"
        if message:
            return message.split(":")[-1].strip()[:120]
    return None


async def _enrich_with_workers(
    k8s, tenant: TenantResponse,
) -> TenantResponse:
    """Add worker count info from MachineDeployment."""
    try:
        result = await k8s.custom_api.list_namespaced_custom_object(
            group=CAPI_GROUP,
            version=CAPI_VERSION,
            namespace=tenant.namespace,
            plural="machinedeployments",
        )
        for md in result.get("items", []):
            md_status = md.get("status", {})
            md_spec = md.get("spec", {})
            tenant.worker_count = md_spec.get("replicas", 0)
            tenant.workers_ready = await _healthy_worker_count(
                k8s, tenant.namespace, md_status.get("readyReplicas", 0),
            )
            tenant.rollout_stalled = await _rollout_stall(
                k8s, tenant.namespace, md_spec, md_status,
            )

            # Extract VM spec from infrastructure template
            infra_ref = md_spec.get("template", {}).get("spec", {}).get("infrastructureRef", {})
            if infra_ref.get("kind") == "KubevirtMachineTemplate":
                try:
                    tpl = await k8s.custom_api.get_namespaced_custom_object(
                        group=KUBEVIRT_INFRA_GROUP,
                        version=KUBEVIRT_INFRA_VERSION,
                        namespace=tenant.namespace,
                        plural="kubevirtmachinetemplates",
                        name=infra_ref.get("name", ""),
                    )
                    vm_spec = (
                        tpl.get("spec", {})
                        .get("template", {})
                        .get("spec", {})
                        .get("virtualMachineTemplate", {})
                        .get("spec", {})
                        .get("template", {})
                        .get("spec", {})
                        .get("domain", {})
                    )
                    tenant.worker_vcpu = vm_spec.get("cpu", {}).get("cores", 0)
                    tenant.worker_memory = vm_spec.get("memory", {}).get("guest", "")
                except ApiException:
                    pass
            break  # only first MachineDeployment
    except ApiException as e:
        logger.debug(f"Could not fetch MachineDeployments for {tenant.name}: {e}")

    return tenant


async def _enrich_with_control_plane(k8s, tenant: TenantResponse) -> TenantResponse:
    """Fill CP replica counts from the KamajiControlPlane CR.

    The CAPI Cluster status only carries a `controlPlaneReady` bool, not
    replica counts — those live on the KamajiControlPlane status
    (replicas / readyReplicas), mirroring the underlying Kamaji TCP. Without
    this the UI showed "0 replicas" for a healthy 2-replica control plane.
    """
    try:
        kcp = await k8s.custom_api.get_namespaced_custom_object(
            group=KAMAJI_CP_GROUP, version=KAMAJI_CP_VERSION,
            namespace=tenant.namespace, plural="kamajicontrolplanes", name=tenant.name,
        )
    except ApiException as e:
        if e.status != 404:
            logger.debug(f"Could not fetch KamajiControlPlane for {tenant.name}: {e}")
        return tenant

    kcp_spec = kcp.get("spec", {})
    kcp_status = kcp.get("status", {})
    # Desired: spec.replicas (fall back to status.replicas).
    tenant.control_plane_replicas = kcp_spec.get(
        "replicas", kcp_status.get("replicas", tenant.control_plane_replicas)
    )
    # Ready: prefer readyReplicas; else status.replicas when marked ready.
    ready = kcp_status.get("readyReplicas")
    if ready is None:
        ready = kcp_status.get("replicas", 0) if kcp_status.get("ready") else 0
    tenant.control_plane_ready_replicas = ready or 0

    # The K8S VERSION column was empty for every tenant. It was read from
    # `Cluster.status.version`, which CAPI leaves unset here — the version this
    # control plane actually runs is `KamajiControlPlane.spec.version`, and it
    # is the only place it appears (the tenant's own Machines carry the kubelet
    # version, which is a different number during an upgrade).
    if not tenant.kubernetes_version:
        tenant.kubernetes_version = kcp_spec.get("version", "")
    return tenant


async def _enrich_with_worker_os(k8s, tenant: TenantResponse) -> TenantResponse:
    """Whether these workers are Talos, read from what they boot.

    Not from an annotation: `kubevirt-ui.io/worker-type` says vm vs bare metal,
    which is a different question, and nothing records the OS. The root volume
    does — a DataVolume means Talos clones a root per worker, a containerDisk
    means cloud-init — and it is the same fact the scale preflight reads, so
    the page and the quota cannot disagree about what a tenant is.

    The UI needs it to decide whether `talosctl` is even a thing here: a
    cloud-init node runs no apid, and offering a credential that connects to
    nothing is worse than offering none.
    """
    shape = await _current_worker_shape(k8s, tenant.namespace, f"{tenant.name}-workers")
    tenant.worker_os = shape.get("worker_os", "")
    return tenant


async def _enrich_with_cp_address(k8s, tenant: TenantResponse) -> TenantResponse:
    """The address a worker joins through, with the ports that make it usable.

    Read from the control-plane LoadBalancer Service rather than from the
    KamajiControlPlane, because the Service is what MetalLB actually assigned
    and what the node actually dials; `advertiseAddress` is the intent and is
    used only as a fallback. Where neither exists the tenant is reachable
    through the ingress alone, and saying that plainly beats an empty field.
    """
    ports: dict[str, int] = {}
    address = ""
    shared: list[str] = []
    source = "service"

    try:
        services = await k8s.core_api.list_service_for_all_namespaces(
            field_selector="metadata.name!=kubernetes",
        )
    except ApiException as e:
        logger.debug(f"Could not list services for {tenant.name}: {e}")
        services = None

    own = None
    if services is not None:
        for svc in services.items:
            if (svc.metadata.namespace == tenant.namespace
                    and svc.metadata.name == f"{tenant.name}-cp-lb"):
                own = svc
                break

    if own is not None:
        ingress = ((own.status.load_balancer.ingress or [])
                   if own.status and own.status.load_balancer else [])
        address = (ingress[0].ip or "") if ingress else ""
        for port in (own.spec.ports or []):
            # The port *names* are ours; the numbers are what a node dials.
            if port.port and port.name:
                ports[port.name] = port.port
        if address and services is not None:
            for svc in services.items:
                if svc.metadata.namespace == tenant.namespace:
                    continue
                if not svc.metadata.name.endswith("-cp-lb"):
                    continue
                other = ((svc.status.load_balancer.ingress or [])
                         if svc.status and svc.status.load_balancer else [])
                if other and other[0].ip == address:
                    shared.append(svc.metadata.name.removesuffix("-cp-lb"))

    if not address:
        try:
            kcp = await k8s.custom_api.get_namespaced_custom_object(
                group=KAMAJI_CP_GROUP, version=KAMAJI_CP_VERSION,
                namespace=tenant.namespace, plural="kamajicontrolplanes",
                name=tenant.name,
            )
            address = ((kcp.get("spec", {}) or {}).get("network", {}) or {}).get(
                "advertiseAddress", "")
            source = "advertised" if address else "ingress"
        except ApiException:
            source = "ingress"

    if not address:
        # Not "unknown": this tenant has no address of its own, and the join
        # path is the ingress. An empty field would read as a gap in the UI
        # rather than as the fact that there is nothing else to reach.
        # Taken from the endpoint already on this object rather than
        # recomputed: two derivations of the same host can drift, and the two
        # would then sit next to each other on the page disagreeing.
        tenant.control_plane_address = TenantControlPlaneAddress(
            address=(tenant.endpoint or "").removeprefix("https://") or "unknown",
            api_port=443, source="ingress",
        )
        return tenant

    def _port(*names: str) -> int | None:
        for n in names:
            if n in ports:
                return ports[n]
        return None

    tenant.control_plane_address = TenantControlPlaneAddress(
        address=address,
        api_port=_port("api", "kube-apiserver", "apiserver") or 6443,
        konnectivity_port=_port("konnectivity", "konn"),
        trustd_port=_port("trustd"),
        shared_with=sorted(shared),
        source=source,
    )
    return tenant


async def _enrich_with_transit_snat(k8s, tenant: TenantResponse) -> TenantResponse:
    """Show the address the tenant's workers actually leave under.

    The transit guard ACLs are keyed on this address, so it is the one fact
    that decides whether a worker can reach its own control plane — and it was
    nowhere in the API. When the lab carried two SNAT rules for one logical IP,
    both `status.ready: true`, there was no way to tell from here which one was
    programmed. Detail view only: it costs a read per tenant and the list does
    not need it.
    """
    transit = transit_subnet_name()
    if not transit:
        return tenant
    vpc = await tenant_vpc_name(k8s, tenant.name)
    if not vpc:
        return tenant  # a default-overlay tenant does not use the transit path
    try:
        tenant.transit_snat_ip = await effective_snat_address(
            k8s, vpc, f"{vpc}-default", transit,
        )
    except ApiException as e:
        logger.debug(f"Could not read the transit SNAT for {tenant.name}: {e}")
    return tenant


async def _enrich_with_folder_env(k8s, tenant: TenantResponse) -> TenantResponse:
    """Backfill folder/environment from the tenant namespace labels.

    New tenants carry these on the Cluster CR (read in _parse_tenant_response),
    but tenants created before that label was added don't. The tenant namespace
    `tenant-<name>` is reliably stamped with kubevirt-ui.io/folder + environment
    by _create_namespace, so use it as the fallback — needed for the UI to scope
    the tenant list by the global env-namespace selector.
    """
    if tenant.folder and tenant.environment:
        return tenant
    try:
        ns_obj = await k8s.core_api.read_namespace(name=tenant.namespace)
        labels = ns_obj.metadata.labels or {}
        tenant.folder = tenant.folder or labels.get("kubevirt-ui.io/folder", "")
        tenant.environment = tenant.environment or labels.get("kubevirt-ui.io/environment", "")
    except ApiException as e:
        logger.debug(f"Could not read namespace labels for {tenant.name}: {e}")
    return tenant


