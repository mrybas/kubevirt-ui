@router.get("/{name}/talosconfig")
async def get_tenant_talosconfig(
    request: Request, name: str, user: User = Depends(require_admin),
) -> dict[str, Any]:
    """A talosconfig for this tenant's nodes, valid for a day.

    Admin-only, and short-lived: it is an `os:admin` credential for every
    machine in the tenant, which is more than the tenant's own kubeconfig
    grants. Talos has no revocation worth the name, so the expiry is the
    control.

    Refused for a cloud-init tenant rather than returned empty — those nodes
    run no Talos API, and a file that connects to nothing is worse than a
    message saying why.
    """
    k8s = request.app.state.k8s_client
    ns = _tenant_ns(name)

    nodes = await _talos_node_addresses(k8s, ns)
    if not nodes:
        raise HTTPException(
            status_code=409,
            detail=(
                f"Tenant {name!r} has no running Talos machine to talk to. "
                "talosctl speaks to each node's apid on :50000; there is "
                "nothing to point it at yet."
            ),
        )

    try:
        secret = await k8s.core_api.read_namespaced_secret(
            name=f"{name}-talos-ca", namespace=ns,
        )
    except ApiException as e:
        if e.status == 404:
            raise HTTPException(
                status_code=404,
                detail=(
                    f"Tenant {name!r} has no Talos CA ({name}-talos-ca). Only "
                    "Talos tenants have one — a cloud-init tenant's nodes run "
                    "no Talos API to connect to."
                ),
            ) from e
        raise k8s_error_to_http(e, "reading the Talos CA")

    ca_pem, crt_pem, key_pem = issue_client_certificate(
        secret.data or {}, common_name=f"{user.username or 'admin'}@{name}",
    )
    return {
        "tenant": name,
        "nodes": nodes,
        "expires_hours": DEFAULT_TTL_HOURS,
        "talosconfig": build_talosconfig(
            name, nodes=nodes, ca_pem=ca_pem, crt_pem=crt_pem, key_pem=key_pem,
        ),
    }


async def _talos_node_addresses(k8s, ns: str) -> list[str]:
    """Addresses of this tenant's running machines.

    From the VirtualMachineInstances rather than from CAPI: a Machine keeps its
    `addresses` after the VM is gone, and a talosconfig pointing at an address
    nobody answers on looks like a broken credential rather than a stopped
    node.
    """
    try:
        vmis = await k8s.custom_api.list_namespaced_custom_object(
            group="kubevirt.io", version="v1", namespace=ns,
            plural="virtualmachineinstances",
        )
    except ApiException:
        return []

    out: list[str] = []
    for vmi in vmis.get("items", []):
        if ((vmi.get("status") or {}).get("phase")) != "Running":
            continue
        for iface in ((vmi.get("status") or {}).get("interfaces") or []):
            ip = iface.get("ipAddress")
            if ip:
                out.append(ip)
                break
    return sorted(out)


def _kubeconfig_with_external_server(kubeconfig_yaml: str, host: str) -> str:
    """Point a tenant kubeconfig at the address a workstation can reach.

    Kamaji writes its Secret against the in-cluster address — on this stand a
    private VIP, unreachable from anywhere an operator sits. The hostname in
    `certSANs` is the one that resolves publicly and is valid in the
    apiserver certificate, so the swap keeps TLS verifiable rather than
    trading it for `insecure-skip-tls-verify`.

    Extracted from the route so it can be tested: the rewrite was correct and
    entirely unguarded, and a kubeconfig that hands back the internal address
    fails only on someone else's machine, long after the change that caused it.
    """
    parsed = yaml.safe_load(kubeconfig_yaml)
    for cluster in parsed.get("clusters", []):
        cluster.setdefault("cluster", {})["server"] = f"https://{host}"
    return yaml.dump(parsed, default_flow_style=False)


@router.get("/{name}/kubeconfig", response_model=TenantKubeconfigResponse)
async def get_tenant_kubeconfig(
    request: Request,
    name: str,
    type: str = "admin",  # "admin" or "oidc"
    user: User = Depends(require_auth),
) -> TenantKubeconfigResponse:
    """Get tenant kubeconfig.

    type=admin  → certificate-based admin kubeconfig (from Kamaji secret)
    type=oidc   → OIDC kubeconfig for end-users (uses current user's token or exec plugin)
    """
    k8s = request.app.state.k8s_client
    await require_tenant_access(k8s, user, name, level="admin")
    await _ensure_cluster_config(k8s)
    ns = _tenant_ns(name)

    # Try CAPI kubeconfig first ({name}-kubeconfig, key: value), fall back to
    # Kamaji admin-kubeconfig ({name}-admin-kubeconfig, key: super-admin.conf)
    secret = None
    for secret_name in [f"{name}-kubeconfig", f"{name}-admin-kubeconfig"]:
        try:
            secret = await k8s.core_api.read_namespaced_secret(
                name=secret_name, namespace=ns,
            )
            break
        except ApiException as e:
            if e.status != 404:
                raise k8s_error_to_http(e, "tenant operation")

    if secret is None:
        raise HTTPException(
            status_code=404,
            detail=f"Kubeconfig not ready yet for tenant '{name}'",
        )

    kubeconfig_data = secret.data or {}

    if type == "admin":
        # Return admin kubeconfig with external endpoint
        raw = kubeconfig_data.get("admin.conf") or kubeconfig_data.get(
            "super-admin.conf"
        ) or kubeconfig_data.get("value", "")

        if not raw:
            raise HTTPException(
                status_code=404, detail="Kubeconfig data not found in secret"
            )

        return TenantKubeconfigResponse(
            kubeconfig=_kubeconfig_with_external_server(
                base64.b64decode(raw).decode("utf-8"), _endpoint_host(name),
            ),
        )

    # type == "oidc"
    if not OIDC_ISSUER:
        raise HTTPException(
            status_code=400,
            detail="OIDC not configured on this cluster. Set OIDC_ISSUER env var.",
        )

    # Extract CA and server from admin kubeconfig
    raw_admin = kubeconfig_data.get("admin.conf") or kubeconfig_data.get(
        "super-admin.conf"
    ) or kubeconfig_data.get("value", "")
    if not raw_admin:
        raise HTTPException(
            status_code=404, detail="Admin kubeconfig not found in secret"
        )

    admin_kc = yaml.safe_load(base64.b64decode(raw_admin).decode("utf-8"))
    clusters = admin_kc.get("clusters", [])
    ca_data = ""
    server = f"https://{_endpoint_host(name)}"
    if clusters:
        cluster_info = clusters[0].get("cluster", {})
        ca_data = cluster_info.get("certificate-authority-data", "")
        # Use the external endpoint, not the internal one from kubeconfig
        # server is already set above

    # Try to get user's current token from Authorization header
    user_token = ""
    auth_header = request.headers.get("Authorization", "")
    if auth_header.startswith("Bearer "):
        user_token = auth_header[7:]

    # Build OIDC kubeconfig
    if user_token:
        # Token-based: embed current user's OIDC token directly
        oidc_kubeconfig = {
            "apiVersion": "v1",
            "kind": "Config",
            "clusters": [{
                "name": name,
                "cluster": {
                    "server": server,
                    "certificate-authority-data": ca_data,
                },
            }],
            "contexts": [{
                "name": name,
                "context": {
                    "cluster": name,
                    "user": "oidc-user",
                },
            }],
            "current-context": name,
            "users": [{
                "name": "oidc-user",
                "user": {
                    "token": user_token,
                },
            }],
        }
    else:
        # Exec-based: use kubelogin/oidc-login plugin
        oidc_kubeconfig = {
            "apiVersion": "v1",
            "kind": "Config",
            "clusters": [{
                "name": name,
                "cluster": {
                    "server": server,
                    "certificate-authority-data": ca_data,
                },
            }],
            "contexts": [{
                "name": name,
                "context": {
                    "cluster": name,
                    "user": "oidc-user",
                },
            }],
            "current-context": name,
            "users": [{
                "name": "oidc-user",
                "user": {
                    "exec": {
                        "apiVersion": "client.authentication.k8s.io/v1beta1",
                        "command": "kubectl",
                        "args": [
                            "oidc-login",
                            "get-token",
                            f"--oidc-issuer-url={OIDC_ISSUER}",
                            f"--oidc-client-id={OIDC_CLIENT_ID}",
                            "--oidc-extra-scope=email",
                            "--oidc-extra-scope=groups",
                            "--oidc-extra-scope=openid",
                        ],
                    },
                },
            }],
        }

    kubeconfig_str = yaml.dump(oidc_kubeconfig, default_flow_style=False)
    return TenantKubeconfigResponse(kubeconfig=kubeconfig_str)


