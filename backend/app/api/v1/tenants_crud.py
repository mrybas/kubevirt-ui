_STORAGE_ADDONS = {"kubevirt-csi-driver"}


async def _tenant_storage_enabled(k8s, name: str) -> bool:
    """Whether the tenant was created with storage passthrough.

    The marker is the KubevirtCluster's `infraClusterSecretRef`: that is what
    lets CAPK — and the CSI driver behind it — talk to the host cluster.
    """
    try:
        kvc = await k8s.custom_api.get_namespaced_custom_object(
            group=KUBEVIRT_INFRA_GROUP, version=KUBEVIRT_INFRA_VERSION,
            namespace=_tenant_ns(name), plural="kubevirtclusters", name=name,
        )
    except Exception:
        return False
    return bool((kvc.get("spec") or {}).get("infraClusterSecretRef"))

@router.post("/{name}/addons", status_code=201)
async def enable_addon(
    request: Request, name: str, addon: TenantAddon,
    user: User = Depends(require_auth),
) -> TenantAddonStatus:
    """Enable an addon for a tenant."""
    k8s = request.app.state.k8s_client
    await require_tenant_access(k8s, user, name, level="member")
    ns = _tenant_ns(name)
    catalog = await _get_addon_catalog(k8s)

    component = catalog.get_component(addon.addon_id)
    if not component:
        raise HTTPException(status_code=404, detail=f"Addon '{addon.addon_id}' not in catalog")

    # The CSI driver is useless — and silently stuck — without the host-side
    # credentials that only `enable_storage` at creation puts in place.
    #
    # Enabling it on a tenant created without storage looked like it worked:
    # the HelmRelease went to `Running 'install' action with timeout of 15m0s`
    # and stayed there, while `storage/status` said `phase: disabled` and the
    # wiring card that would have explained it is hidden in exactly that
    # state. Refused with the reason instead.
    if addon.addon_id in _STORAGE_ADDONS and not await _tenant_storage_enabled(k8s, name):
        raise HTTPException(
            status_code=409,
            detail=(
                f"Tenant '{name}' was created without storage, so the "
                f"host-side CSI credentials it needs do not exist. The driver "
                f"would install and then wait for them indefinitely. Recreate "
                f"the tenant with storage enabled."
            ),
        )

    # Merge defaults with user params
    params: dict[str, str] = {}
    for p in component.parameters:
        params[p.id] = addon.parameters.get(p.id, p.default)

    try:
        # If new addon has a target namespace, patch the namespaces HelmRelease
        if component.namespace:
            # Prefix namespace with tenant name for non-core addons
            target_ns = (
                f"{name}-{component.namespace}"
                if component.category != "core"
                else component.namespace
            )
            ns_hr_name = f"{name}-namespaces"
            try:
                ns_hr = await k8s.custom_api.get_namespaced_custom_object(
                    group=FLUX_HELM_GROUP, version=FLUX_HELM_VERSION,
                    namespace=ns, plural="helmreleases", name=ns_hr_name,
                )
                existing_ns = ns_hr.get("spec", {}).get("values", {}).get("namespaces", [])
                ns_names = {n["name"] for n in existing_ns}
                if target_ns not in ns_names:
                    existing_ns.append({"name": target_ns})
                    await k8s.custom_api.patch_namespaced_custom_object(
                        group=FLUX_HELM_GROUP, version=FLUX_HELM_VERSION,
                        namespace=ns, plural="helmreleases", name=ns_hr_name,
                        body={"spec": {"values": {"namespaces": existing_ns}}},
                        _content_type="application/merge-patch+json",
                    )
            except ApiException:
                pass  # namespaces HR not found — skip

        # Build Helm values and create HelmRelease
        helm_values = _build_helm_values(name, component, params)

        # dependsOn: everything depends on CNI
        cni_addon_id = None
        for c in catalog.components:
            if c.required and c.category == "networking":
                cni_addon_id = c.id
                break

        depends_on = None
        if cni_addon_id and addon.addon_id != cni_addon_id:
            depends_on = [f"{name}-{cni_addon_id}"]

        hr_body = _build_flux_helmrelease_cr(
            tenant_name=name,
            addon_id=addon.addon_id,
            component=component,
            catalog=catalog,
            helm_values=helm_values,
            depends_on=depends_on,
        )
        await k8s.custom_api.create_namespaced_custom_object(
            group=FLUX_HELM_GROUP,
            version=FLUX_HELM_VERSION,
            namespace=ns,
            plural="helmreleases",
            body=hr_body,
        )

        return TenantAddonStatus(
            addon_id=addon.addon_id,
            name=f"{name}-{addon.addon_id}",
            ready=False,
            message="Created, waiting for reconciliation",
        )

    except ApiException as e:
        if e.status == 409:
            raise HTTPException(
                status_code=409,
                detail=f"Addon '{addon.addon_id}' already enabled",
            )
        raise k8s_error_to_http(e, "tenant operation")


